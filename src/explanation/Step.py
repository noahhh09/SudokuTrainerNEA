class Step:
    def __init__(self, text: str, stackable: bool = False):
        self.text = text
        self.stackable = stackable

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        if len(self.text) > 0:
            infoLabel.configure(text=self.text)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        pass

# Note for Steps, always place the text to be shown in the last step's text value Every other text value can be empty.
class Steps(Step):
    def __init__(self, steps: list[Step], stackable: bool = False) -> None:
        self.steps = steps
        self.stackable = stackable

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        for step in self.steps:
            step.apply(renderer, infoLabel)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        for step in reversed(self.steps):
            step.undo(renderer, infoLabel)

