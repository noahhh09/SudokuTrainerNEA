class ApplyMove(Step):
    def __init__(self, text: str, move: Move, stackable: bool = False):
        self.move = move
        super().__init__(text, stackable)

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        self.move.apply(renderer.boardState)
        renderer.redraw()
        return super().apply(renderer, infoLabel)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        self.move.undo(renderer.boardState)
        renderer.redraw()
        return super().undo(renderer, infoLabel)

class ApplyMoves(Step):
    def __init__(self, text: str, moves: list[Move], stackable: bool = False):
        self.moves = moves
        super().__init__(text, stackable)

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        for move in self.moves:
            move.apply(renderer.boardState)
        renderer.redraw()
        return super().apply(renderer, infoLabel)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        for move in reversed(self.moves):
            move.undo(renderer.boardState)
        renderer.redraw()
        return super().undo(renderer, infoLabel)