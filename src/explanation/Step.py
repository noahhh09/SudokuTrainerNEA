class HighlightCells(Step):
    def __init__(self, text: str, positionsOrUnit: list[tuple[int, int]] | Unit, colour: str = "#FCFC76", stackable: bool = False):
        super().__init__(text, stackable)
        self.colour = colour

        if type(positionsOrUnit) is list:
            self.cells = positionsOrUnit
        elif type(positionsOrUnit) is Unit:
            self.cells = [positionsOrUnit.getBoardPosition(i) for i in range(9)]

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        renderer.highlightCells(self.cells, self.colour)
        return super().apply(renderer, infoLabel)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        renderer.highlightCells(self.cells, "white")
        return super().undo(renderer, infoLabel)

class PopulateLogicalCandidatesInCells(Step):
    def __init__(self, text: str, positionsOrUnit: list[tuple[int, int]] | Unit, stackable: bool = False):
        super().__init__(text, stackable)
        if type(positionsOrUnit) is list:
            self.cells = positionsOrUnit
        elif type(positionsOrUnit) is Unit:
            self.cells = [positionsOrUnit.getBoardPosition(i) for i in range(9)]

    def apply(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        board = renderer.boardState
        candidates = BoardUtils.getCandidatesMatrix(board)

        for row, col in self.cells:
            board.getCell(row, col).addCandidates(candidates[row][col])
            renderer.redrawCell(row, col)

        return super().apply(renderer, infoLabel)

    def undo(self, renderer: SudokuGrid, infoLabel: ctk.CTkLabel):
        board = renderer.boardState
        candidates = BoardUtils.getCandidatesMatrix(board)

        for row, col in self.cells:
            board.getCell(row, col).removeCandidates(candidates[row][col])
            renderer.redrawCell(row, col)

        return super().undo(renderer, infoLabel)

